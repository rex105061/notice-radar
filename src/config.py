# --------------------------------------------------------------------------
# 公告分类规则（⚠️ 初版，最终归类权归项目作者）
#
# 背景：A 股每日约 1000–1500 条公告，其中大部分是"会议决议 / 股东大会通知"
# 这类零解读价值的内容。随机抽样会让评测集大量空转。
# 这组规则把公告分成「高价值 / 低价值 / 其他」，用于从全量库里抽定向子集。
#
# 匹配顺序：先判低位噪音（LOW_VALUE），再判高价值（HIGH_VALUE）。
# 原因："关于召开第三届董事会第十次会议的通知"同时含"董事"和"会议通知"，
#       必须先被噪音规则拦下，否则会被误判成"人事变动"。
# --------------------------------------------------------------------------
LOW_VALUE_RULES = [
    # 中介机构出具的佐证文件。实测占「未解析正文」的绝大多数：体积大（几十到上百 MB）、
    # 多为盖章扫描件、且不是 IR 的解读对象。不单独归一类，会把评测集稀释掉。
    ("中介机构文件", ["审计报告", "审阅报告", "法律意见书", "核查意见",
                      "验资报告", "评估报告", "财务报表及审计"]),
    # 港交所 / 境外治理文件。A+H 公司常见，对 A 股 IR 解读价值低。
    ("境外治理文件", ["H股", "多元化政策", "股东提名", "企业管治", "境外上市"]),
    # 个人事务类：独董培训承诺函、任职资格声明等，无解读价值。
    # 实测踩坑：这类标题含「独立董事」，会被误判成「人事变动」（高价值）。
    ("个人事务类", ["承诺函", "培训", "声明与承诺", "任职资格"]),
    # 程序性提示：正文只说「将于某日披露定期报告」，本身没有信息量。
    ("程序性提示", ["报告披露的提示性公告", "披露提示性公告", "披露的提示性公告"]),
    ("会议类", ["股东大会", "董事会决议", "监事会决议", "会议决议", "会议通知",
                "会议资料", "独立董事意见", "独立董事专门会议", "会议材料"]),
    ("制度章程类", ["公司章程", "管理制度", "议事规则", "信息披露事务", "内幕信息"]),
]

HIGH_VALUE_RULES = [
    ("业绩与定期报告", ["业绩预告", "业绩快报", "年度报告", "半年度报告", "季度报告",
                        "主要经营数据", "经营情况公告"]),
    ("重大合同与订单", ["重大合同", "中标", "框架协议", "战略合作", "采购合同",
                        "销售合同", "日常经营重大合同"]),
    ("股权变动", ["增持", "减持", "权益变动", "协议转让", "要约收购", "股份回购",
                  "回购股份", "解除限售", "股份质押", "解除质押", "司法冻结", "司法拍卖"]),
    ("并购重组", ["重大资产重组", "资产置换", "吸收合并", "收购", "出售资产",
                  "股权收购", "资产收购", "股权转让"]),
    ("融资事项", ["可转换公司债券", "非公开发行", "向特定对象发行", "公司债券",
                  "中期票据", "超短期融资券", "配股", "发行股份购买"]),
    ("关联交易与担保", ["关联交易", "对外担保", "资金占用", "提供担保"]),
    ("风险事项", ["诉讼", "仲裁", "立案调查", "行政处罚", "监管函", "警示函",
                  "退市风险", "风险警示", "终止上市", "问询函", "债务逾期"]),
    ("利润分配", ["利润分配", "权益分派", "分红", "派息"]),
    ("薪酬与激励", ["薪酬方案", "股权激励", "限制性股票", "员工持股", "激励计划",
                    "绩效考核", "薪酬制度"]),
    ("人事变动", ["辞职", "聘任", "换届", "离任", "高级管理人员", "董事", "监事"]),
    ("对外投资", ["对外投资", "设立子公司", "投资设立", "增资", "参股"]),
]


def classify_title(title: str) -> tuple:
    """按标题关键词归类公告。

    Returns:
        (类别名, is_high_value)  is_high_value: 1=高价值定向子集, 0=其他/噪音
    """
    if not title:
        return ("未分类", 0)
    for cat, kws in LOW_VALUE_RULES:
        if any(k in title for k in kws):
            return (cat, 0)
    for cat, kws in HIGH_VALUE_RULES:
        if any(k in title for k in kws):
            return (cat, 1)
    return ("其他", 0)
